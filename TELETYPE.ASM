; TELETYPE/CMD v1.1 - TRS-80 Model III native Z80 teletype
; TRSDOS/LDOS command file; 48K Model III, RS-232 option.
; Origin 7000h keeps clear of TRSDOS library command overlays.
; No BASIC or memory-size reservation required.
; Full-width paper: 64 columns, rows 0..14; printhead on row 15.
; Local screen-test mode has no artificial baud-rate delays.
; Ctrl-] (1Dh) exits to DOS READY. Real serial expects remote echo.

        ORG     7000H

START:  CALL    01C9H           ; ROM clear display
        LD      HL,MSG_TITLE
        LD      DE,3C40H        ; screen row 1
        CALL    PRINT_AT
        LD      HL,MSG_MODE
        LD      DE,3CC0H        ; row 3
        CALL    PRINT_AT
        LD      HL,MSG_LOCAL
        LD      DE,3D40H        ; row 5
        CALL    PRINT_AT
        LD      HL,MSG_SERIAL
        LD      DE,3D80H        ; row 6
        CALL    PRINT_AT
        LD      HL,MSG_CHOOSE
        LD      DE,3E00H        ; row 8
        CALL    PRINT_AT

MODE_KEY:
        CALL    0049H           ; ROM wait for keyboard key
        CP      '2'
        JP      Z,BAUD_MENU
        CP      '1'
        JP      Z,LOCAL_SELECTED
        CP      0DH             ; Enter = default local
        JR      NZ,MODE_KEY

LOCAL_SELECTED:
        XOR     A
        LD      (MODE),A
        JP      RUN_INIT

BAUD_MENU:
        LD      A,1
        LD      (MODE),A
        LD      A,0EEH          ; default 9600 baud, TX and RX
        LD      (BAUD),A
        CALL    01C9H
        LD      HL,MSG_TITLE
        LD      DE,3C40H
        CALL    PRINT_AT
        LD      HL,MSG_BAUD
        LD      DE,3CC0H
        CALL    PRINT_AT
        LD      HL,MSG_9600
        LD      DE,3D40H
        CALL    PRINT_AT
        LD      HL,MSG_300
        LD      DE,3D80H
        CALL    PRINT_AT
        LD      HL,MSG_CHOOSE
        LD      DE,3E00H
        CALL    PRINT_AT

BAUD_KEY:
        CALL    0049H
        CP      '2'
        JR      Z,BAUD_300
        CP      '1'
        JR      Z,SERIAL_SELECTED
        CP      0DH
        JR      NZ,BAUD_KEY
        JR      SERIAL_SELECTED

BAUD_300:
        LD      A,055H          ; Model III 300 baud both ways
        LD      (BAUD),A

SERIAL_SELECTED:
        XOR     A
        OUT     (0E8H),A       ; reset UART
        LD      A,(BAUD)
        OUT     (0E9H),A       ; set baud (EEH 9600; 55H 300)
        LD      A,068H
        OUT     (0EAH),A       ; 8N1, parity off, DTR/RTS asserted

RUN_INIT:
        CALL    01C9H           ; erase startup menus completely
        LD      A,0FH           ; Model III ROM: disable flashing cursor
        CALL    0033H           ; keep only our ^ printhead visible
        LD      HL,3F80H       ; paper printing line, screen row 14
        LD      (PRINTPTR),HL
        LD      HL,3FC0H       ; printhead row 15
        LD      (HEADPTR),HL
        XOR     A
        LD      (COLUMN),A
        LD      (PENDING_CR),A
        LD      A,'^'
        LD      (3FC0H),A
        LD      A,(MODE)
        OR      A
        JP      Z,LOCAL_LOOP
        JP      SERIAL_LOOP

; Local mode: read directly from ROM keyboard, immediately display.
LOCAL_LOOP:
        CALL    002BH           ; one keyboard scan, no echo
        OR      A
        JR      Z,LOCAL_LOOP
        CP      01DH            ; Ctrl-]
        JP      Z,QUIT
        CP      0DH             ; CR / Enter
        JR      Z,LOCAL_FEED
        CP      0AH             ; LF, if generated by keyboard
        JR      Z,LOCAL_FEED
        CP      08H
        JR      Z,LOCAL_BACK
        CP      020H
        JR      C,LOCAL_LOOP
        CP      07FH
        JR      NC,LOCAL_LOOP
        CALL    PRINTCHAR
        JR      LOCAL_LOOP

LOCAL_FEED:
        CALL    LINEFEED
        JP      LOCAL_LOOP
LOCAL_BACK:
        CALL    BACKSPACE
        JP      LOCAL_LOOP

; Real RS-232: send raw key bytes, show only received bytes.
; Half/full duplex selectable echo semantics are future work.
SERIAL_LOOP:
        IN      A,(0EAH)       ; UART status
        BIT     7,A            ; received byte available?
        JR      Z,SERIAL_KEY
        IN      A,(0EBH)
        CALL    RECEIVE
SERIAL_KEY:
        CALL    002BH
        OR      A
        JR      Z,SERIAL_LOOP
        CP      01DH
        JP      Z,QUIT
        LD      B,A
SERIAL_WAIT:
        IN      A,(0EAH)
        BIT     6,A            ; TX holding register empty/sent?
        JR      Z,SERIAL_WAIT
        LD      A,B
        OUT     (0EBH),A
        JR      SERIAL_LOOP

; Incoming serial data: CRLF counts as one paper feed.
RECEIVE:
        CP      0DH
        JR      Z,REC_CR
        CP      0AH
        JR      Z,REC_LF
        LD      B,A
        XOR     A
        LD      (PENDING_CR),A
        LD      A,B
        CP      08H
        JR      Z,REC_BS
        CP      020H
        RET     C
        CP      07FH
        RET     NC
        CALL    PRINTCHAR
        RET
REC_CR:
        LD      A,1
        LD      (PENDING_CR),A
        JP      LINEFEED
REC_LF:
        LD      A,(PENDING_CR)
        OR      A
        JR      Z,REC_LF_NEW
        XOR     A
        LD      (PENDING_CR),A
        RET
REC_LF_NEW:
        JP      LINEFEED
REC_BS:
        JP      BACKSPACE

; Print one character in A at row 14, move ^ exactly one column.
; Never write past video RAM when column wraps from 63 to 0.
PRINTCHAR:
        LD      HL,(PRINTPTR)
        LD      (HL),A
        LD      HL,(HEADPTR)
        LD      (HL),020H
        LD      A,(COLUMN)
        INC     A
        LD      (COLUMN),A
        CP      64
        JP      Z,LINEFEED
        LD      HL,(PRINTPTR)
        INC     HL
        LD      (PRINTPTR),HL
        LD      HL,(HEADPTR)
        INC     HL
        LD      (HEADPTR),HL
        LD      (HL),'^'
        RET

; Scroll only paper rows 0..14, leaving head row 15 fixed.
; 14 * 64 = 896 bytes (0380h) moved with LDIR.
LINEFEED:
        LD      HL,3C40H       ; row 1
        LD      DE,3C00H       ; row 0
        LD      BC,0380H
        LDIR
        LD      HL,3F80H       ; row 14 clear 64 cells
        LD      (HL),020H
        LD      DE,3F81H
        LD      BC,003FH
        LDIR
        LD      HL,(HEADPTR)
        LD      (HL),020H
        LD      HL,3FC0H
        LD      (HEADPTR),HL
        LD      (HL),'^'
        LD      HL,3F80H
        LD      (PRINTPTR),HL
        XOR     A
        LD      (COLUMN),A
        RET

BACKSPACE:
        LD      A,(COLUMN)
        OR      A
        RET     Z
        DEC     A
        LD      (COLUMN),A
        LD      HL,(HEADPTR)
        LD      (HL),020H
        DEC     HL
        LD      (HEADPTR),HL
        LD      (HL),'^'
        LD      HL,(PRINTPTR)
        DEC     HL
        LD      (PRINTPTR),HL
        LD      (HL),020H
        RET

; Copy zero-terminated string HL to video address DE.
PRINT_AT:
        LD      A,(HL)
        OR      A
        RET     Z
        LD      (DE),A
        INC     HL
        INC     DE
        JR      PRINT_AT

QUIT:
        LD      A,0EH           ; restore ROM cursor for DOS prompt
        CALL    0033H
        JP      402DH          ; TRSDOS/LDOS DOS READY reentry

MODE:       DEFB 0
BAUD:       DEFB 0EEH
COLUMN:     DEFB 0
PENDING_CR: DEFB 0
PRINTPTR:   DEFW 3F80H
HEADPTR:    DEFW 3FC0H
MSG_TITLE:  DEFM "TRS-80 MODEL III TELETYPE/CMD V1.1"
            DEFB 0
MSG_MODE:   DEFM "SELECT OPERATING MODE"
            DEFB 0
MSG_LOCAL:  DEFM "1 - LOCAL SCREEN TEST (DEFAULT)"
            DEFB 0
MSG_SERIAL: DEFM "2 - REAL RS232 SERIAL PORT"
            DEFB 0
MSG_BAUD:   DEFM "REAL RS232 - SELECT BAUD (8N1)"
            DEFB 0
MSG_9600:   DEFM "1 - 9600 BAUD (DEFAULT)"
            DEFB 0
MSG_300:    DEFM "2 - 300 BAUD"
            DEFB 0
MSG_CHOOSE: DEFM "PRESS 1, 2 OR ENTER"
            DEFB 0

        END START
