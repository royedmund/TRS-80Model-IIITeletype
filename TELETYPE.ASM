; TELETYPE/CMD v1.6 - TRS-80 Model III native Z80 teletype
; TRSDOS/LDOS command file; 48K Model III, RS-232 option.
; Origin 7000h keeps clear of TRSDOS library command overlays.
; No BASIC or memory-size reservation required.
; 80-character logical lines on 64-column screen; row 15 printhead.
; Local screen-test mode has no artificial baud-rate delays.
; Ctrl-] quits. Full duplex=remote echo; half duplex=local echo.
; Bell once on logical character 80, then automatic paper feed.
; Bell generated via Model III cassette output port FFh; needs audio monitoring.

        ORG     7000H

START:  CALL    01C9H           ; ROM clear display
        LD      HL,MSG_TITLE
        LD      DE,3C40H        ; screen row 1
        CALL    PRINT_AT
        LD      HL,MSG_MODE
        LD      DE,3CC0H        ; row 3
        CALL    PRINT_AT
        LD      HL,MSG_LOCAL
        LD      DE,3D40H        ; row 5
        CALL    PRINT_AT
        LD      HL,MSG_SERIAL
        LD      DE,3D80H        ; row 6
        CALL    PRINT_AT
        LD      HL,MSG_CHOOSE
        LD      DE,3E00H        ; row 8
        CALL    PRINT_AT

MODE_KEY:
        CALL    WAIT_KEY           ; ROM wait for keyboard key
        CP      '2'
        JP      Z,BAUD_MENU
        CP      '1'
        JP      Z,LOCAL_SELECTED
        CP      0DH             ; Enter = default local
        JR      NZ,MODE_KEY

LOCAL_SELECTED:
        XOR     A
        LD      (MODE),A
        JP      RUN_INIT

BAUD_MENU:
        LD      A,1
        LD      (MODE),A
        LD      A,0EEH          ; default 9600 baud, TX and RX
        LD      (BAUD),A
        CALL    01C9H
        LD      HL,MSG_TITLE
        LD      DE,3C40H
        CALL    PRINT_AT
        LD      HL,MSG_BAUD
        LD      DE,3CC0H
        CALL    PRINT_AT
        LD      HL,MSG_9600
        LD      DE,3D40H
        CALL    PRINT_AT
        LD      HL,MSG_300
        LD      DE,3D80H
        CALL    PRINT_AT
        LD      HL,MSG_CHOOSE
        LD      DE,3E00H
        CALL    PRINT_AT

BAUD_KEY:
        CALL    WAIT_KEY
        CP      '2'
        JR      Z,BAUD_300
        CP      '1'
        JR      Z,DUPLEX_MENU
        CP      0DH
        JR      NZ,BAUD_KEY
        JR      DUPLEX_MENU

BAUD_300:
        LD      A,055H          ; Model III 300 baud both ways
        LD      (BAUD),A

; Duplex selection is serial-only.  Full = remote echo, half = local.
DUPLEX_MENU:
        XOR     A
        LD      (DUPLEX),A     ; full duplex is default
        CALL    01C9H
        LD      HL,MSG_TITLE
        LD      DE,3C40H
        CALL    PRINT_AT
        LD      HL,MSG_DUPLEX
        LD      DE,3CC0H
        CALL    PRINT_AT
        LD      HL,MSG_FULL
        LD      DE,3D40H
        CALL    PRINT_AT
        LD      HL,MSG_HALF
        LD      DE,3D80H
        CALL    PRINT_AT
        LD      HL,MSG_CHOOSE
        LD      DE,3E00H
        CALL    PRINT_AT
DUPLEX_KEY:
        CALL    WAIT_KEY
        CP      '2'
        JR      Z,SET_HALF
        CP      '1'
        JR      Z,SERIAL_SELECTED
        CP      0DH
        JR      NZ,DUPLEX_KEY
        JR      SERIAL_SELECTED
SET_HALF:
        LD      A,1
        LD      (DUPLEX),A

SERIAL_SELECTED:
        XOR     A
        OUT     (0E8H),A       ; reset UART
        LD      A,(BAUD)
        OUT     (0E9H),A       ; set baud (EEH 9600; 55H 300)
        LD      A,06CH          ; 8N1, transmitter enabled
        OUT     (0EAH),A       ; 8N1, transmitter enabled, DTR/RTS active

RUN_INIT:
        CALL    01C9H           ; erase startup menus completely
        LD      A,0FH           ; Model III ROM: disable flashing cursor
        CALL    0033H           ; keep only our ^ printhead visible
        LD      HL,3F80H       ; paper printing line, screen row 14
        LD      (PRINTPTR),HL
        LD      HL,3FC0H       ; printhead row 15
        LD      (HEADPTR),HL
        XOR     A
        LD      (COLUMN),A
        LD      (LINECOUNT),A
        LD      (PENDING_CR),A
        LD      A,'^'
        LD      (3FC0H),A
        LD      A,(MODE)
        OR      A
        JP      Z,LOCAL_LOOP
        JP      SERIAL_LOOP

; Local mode: read directly from ROM keyboard, immediately display.
LOCAL_LOOP:
        CALL    GET_KEY           ; one keyboard scan, no echo
        OR      A
        JR      Z,LOCAL_LOOP
        CP      01DH            ; Ctrl-]
        JP      Z,QUIT
        CP      0DH             ; CR / Enter
        JR      Z,LOCAL_FEED
        CP      0AH             ; LF, if generated by keyboard
        JR      Z,LOCAL_FEED
        CP      08H
        JR      Z,LOCAL_BACK
        CP      020H
        JR      C,LOCAL_LOOP
        CP      07FH
        JR      NC,LOCAL_LOOP
        CALL    PRINTCHAR
        JR      LOCAL_LOOP

LOCAL_FEED:
        CALL    LINEFEED
        JP      LOCAL_LOOP
LOCAL_BACK:
        CALL    BACKSPACE
        JP      LOCAL_LOOP

; Real RS-232: incoming data always prints. Outgoing key locally
; prints only in half-duplex mode (remote echo should be disabled).
SERIAL_LOOP:
        IN      A,(0EAH)       ; UART status
        BIT     7,A            ; received byte available?
        JR      Z,SERIAL_KEY
        IN      A,(0EBH)
        CALL    RECEIVE
SERIAL_KEY:
        CALL    GET_KEY
        OR      A
        JR      Z,SERIAL_LOOP
        CP      01DH
        JP      Z,QUIT
        LD      B,A
SERIAL_WAIT:
        CALL    TXREADY       ; BREAK also aborts a blocked UART send
        NOP                    ; hold binary addresses stable for this build
        NOP
        NOP
        LD      A,B
        OUT     (0EBH),A
        LD      A,(DUPLEX)
        OR      A
        JP      Z,SERIAL_CRLF_CHECK  ; full duplex: remote echo
        LD      A,B
        CALL    ECHO_PRESERVE_BC   ; half duplex: display locally
        JP      SERIAL_CRLF_CHECK  ; CR must also transmit LF

; Incoming serial data: CRLF counts as one paper feed.
RECEIVE:
        CP      0DH
        JR      Z,REC_CR
        CP      0AH
        JR      Z,REC_LF
        LD      B,A
        XOR     A
        LD      (PENDING_CR),A
        LD      A,B
        CP      08H
        JR      Z,REC_BS
        CP      020H
        RET     C
        CP      07FH
        RET     NC
        CALL    PRINTCHAR
        RET
REC_CR:
        LD      A,1
        LD      (PENDING_CR),A
        JP      LINEFEED
REC_LF:
        LD      A,(PENDING_CR)
        OR      A
        JR      Z,REC_LF_NEW
        XOR     A
        LD      (PENDING_CR),A
        RET
REC_LF_NEW:
        JP      LINEFEED
REC_BS:
        JP      BACKSPACE

; Count logical 80-character lines independently of 64-column screen.
; At column 64, make a physical row wrap, but retain the logical count.
; At logical character 80, ring the bell once, then CR/LF paper feed.
PRINTCHAR:
        LD      HL,(PRINTPTR)
        LD      (HL),A
        LD      HL,(HEADPTR)
        LD      (HL),020H
        LD      A,(COLUMN)
        INC     A
        LD      (COLUMN),A
        LD      A,(LINECOUNT)
        INC     A
        LD      (LINECOUNT),A
        CP      80
        JP      Z,BELL_NEWLINE
        LD      A,(COLUMN)
        CP      64
        JP      Z,SCROLL_PAPER
        LD      HL,(PRINTPTR)
        INC     HL
        LD      (PRINTPTR),HL
        LD      HL,(HEADPTR)
        INC     HL
        LD      (HEADPTR),HL
        LD      (HL),'^'
        RET

BELL_NEWLINE:
        CALL    BELL
        JP      LINEFEED

; Explicit CR/LF resets logical line length.
LINEFEED:
        CALL    SCROLL_PAPER
        XOR     A
        LD      (LINECOUNT),A
        RET

; Scroll *only* paper rows 0..14, leaving head row 15 fixed.
; 14 * 64 = 896 bytes (0380h) moved with LDIR.
SCROLL_PAPER:
        LD      HL,3C40H       ; row 1
        LD      DE,3C00H       ; row 0
        LD      BC,0380H
        LDIR
        LD      HL,3F80H       ; row 14 clear 64 cells
        LD      (HL),020H
        LD      DE,3F81H
        LD      BC,003FH
        LDIR
        LD      HL,(HEADPTR)
        LD      (HL),020H
        LD      HL,3FC0H
        LD      (HEADPTR),HL
        LD      (HL),'^'
        LD      HL,3F80H
        LD      (PRINTPTR),HL
        XOR     A
        LD      (COLUMN),A
        RET

BACKSPACE:
        LD      A,(COLUMN)
        OR      A
        RET     Z
        DEC     A
        LD      (COLUMN),A
        LD      HL,(HEADPTR)
        LD      (HL),020H
        DEC     HL
        LD      (HEADPTR),HL
        LD      (HL),'^'
        LD      HL,(PRINTPTR)
        DEC     HL
        LD      (PRINTPTR),HL
        LD      (HL),020H
        LD      A,(LINECOUNT)
        DEC     A
        LD      (LINECOUNT),A
        RET

; Short single bell on character 80, via cassette sound output FFh.
; AF and BC are saved so printhead and UART state remain intact.
; This sound will be audible only with cassette audio enabled/connected.
BELL:
        PUSH    AF
        PUSH    BC
        LD      C,80
BELL_CYCLE:
        LD      A,1
        OUT     (0FFH),A
        LD      B,80
BELL_HIGH:
        DJNZ    BELL_HIGH
        XOR     A
        OUT     (0FFH),A
        LD      B,80
BELL_LOW:
        DJNZ    BELL_LOW
        DEC     C
        JR      NZ,BELL_CYCLE
        POP     BC
        POP     AF
        RET

; Copy zero-terminated string HL to video address DE.
PRINT_AT:
        LD      A,(HL)
        OR      A
        RET     Z
        LD      (DE),A
        INC     HL
        INC     DE
        JR      PRINT_AT

QUIT:
        LD      A,0EH           ; restore ROM cursor for DOS prompt
        CALL    0033H
        JP      402DH          ; TRSDOS/LDOS DOS READY reentry

MODE:       DEFB 0
BAUD:       DEFB 0EEH
DUPLEX:     DEFB 0             ; 0=full / remote echo; 1=half / local
COLUMN:     DEFB 0
LINECOUNT:  DEFB 0             ; printable chars since latest CR/LF
PENDING_CR: DEFB 0
PRINTPTR:   DEFW 3F80H
HEADPTR:    DEFW 3FC0H
MSG_TITLE:  DEFM "TRS-80 MODEL III TELETYPE/CMD V1.6"
            DEFB 0
MSG_MODE:   DEFM "SELECT OPERATING MODE"
            DEFB 0
MSG_LOCAL:  DEFM "1 - LOCAL SCREEN TEST (DEFAULT)"
            DEFB 0
MSG_SERIAL: DEFM "2 - REAL RS232 SERIAL PORT"
            DEFB 0
MSG_BAUD:   DEFM "REAL RS232 - SELECT BAUD (8N1)"
            DEFB 0
MSG_9600:   DEFM "1 - 9600 BAUD (DEFAULT)"
            DEFB 0
MSG_300:    DEFM "2 - 300 BAUD"
            DEFB 0
MSG_DUPLEX: DEFM "SELECT SERIAL DUPLEX / ECHO MODE"
            DEFB 0
MSG_FULL:   DEFM "1 - FULL DUPLEX (REMOTE ECHO, DEFAULT)"
            DEFB 0
MSG_HALF:   DEFM "2 - HALF DUPLEX (LOCAL ECHO)"
            DEFB 0
MSG_CHOOSE: DEFM "PRESS 1, 2 OR ENTER"
            DEFB 0

; BREAK hardware key is at 3840H bit 2, also returned as 01H
; by the Model III ROM keyboard scan. Ctrl-] remains supported.
GET_KEY:
        LD      A,(3840H)
        AND     04H
        JP      NZ,QUIT
        CALL    002BH
        CP      01H
        JP      Z,QUIT
        RET

WAIT_KEY:
        CALL    0049H
        CP      01H
        JP      Z,QUIT
        RET

; Poll UART TX-ready bit 6, but do not trap the user indefinitely.
; BREAK exits to DOS even when TX-ready never becomes set.
TXREADY:
        IN      A,(0EAH)
        BIT     6,A
        RET     NZ
        LD      A,(3840H)
        AND     04H
        JP      NZ,QUIT
        JR      TXREADY

; Enter on the TRS-80 transmits CR (0DH) followed by LF (0AH).
; The first byte was transmitted by SERIAL_KEY. This sends LF only
; for Enter, not for other keystrokes. Break exits even when blocked.
SERIAL_CRLF_CHECK:
        LD      A,B
        CP      0DH
        JP      NZ,SERIAL_LOOP
        CALL    TXREADY
        LD      A,0AH
        OUT     (0EBH),A
        JP      SERIAL_LOOP

; RECEIVE and LDIR scrolling may destroy B, which still holds the
; original key. Keep BC across half-duplex local echo for CRLF test.
ECHO_PRESERVE_BC:
        PUSH    BC
        CALL    RECEIVE
        POP     BC
        RET

        END START
